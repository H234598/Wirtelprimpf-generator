import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const prefixes = [
  "",
  "leise",
  "laut",
  "verschlafen",
  "neugierig",
  "empört",
  "zufrieden",
  "hungrig",
  "flüsternd",
  "dramatisch",
];
const sounds = [
  "miau",
  "miauu",
  "miauuu",
  "maooo",
  "mau",
  "mraau",
  "mrrp",
  "mrrrau",
  "nya",
  "njamiau",
  "schnurr",
  "schnurrr",
  "prrr",
  "prrrt",
  "rrrrrr",
  "rrr-miau",
  "maunz",
  "maunzmiau",
  "miep",
  "miau-schnurr",
];
const suffixes = ["", "!", "?", "…", " ♥"];

const replies = prefixes.flatMap((prefix) =>
  sounds.flatMap((sound) =>
    suffixes.map((suffix) => `${prefix ? `${prefix} ` : ""}${sound}${suffix}`),
  ),
);
const normalized = replies.map((reply) =>
  reply.trim().normalize("NFC").toLocaleLowerCase("de-DE"),
);
if (replies.length < 1_000 || new Set(normalized).size !== replies.length) {
  throw new Error(
    `invalid CatGPT reply set: ${replies.length} total, ${new Set(normalized).size} unique`,
  );
}

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, "../src/lib/catgpt/static-replies.generated.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/generate-catgpt-static-replies.mjs.\nexport const STATIC_REPLIES = ${JSON.stringify(replies, null, 2)} as const;\n`,
);
